"""Channel level 2 of Phase A: peers show their state plus a one-sentence
motivation generated by the same model (design notes §5, "stati più una frase
di motivazione generata da ogni vicino"; Cho et al. Reason format, §10.23).

The motivations are sampled once into a pool per label and per model,
with a fixed seed, and drawn from the pool when the prompt for a peer
configuration is built. Two controls are built into the toy:
    * "list": the same configurations without motivations (channel level 1);
    * "shuffled": the same motivation texts attached to random labels, so
      that the effect of extra text is separated from the effect of the
      content agreeing with the shown state.
"""
from __future__ import annotations

import numpy as np

from .phase_a import render_memory
from .tabulate import LABELS, LogitReader

MOTIVATION_PROMPT = (
    "In a game every player holds a state, either {a} or {b}. A player currently holds state {label}. "
    "Write one short sentence, at most 20 words, in which that player explains why they hold state {label}. "
    "Write only the sentence."
)


def generate_text(reader: LogitReader, user_text: str, max_new_tokens: int, temperature: float,
                  seed: int) -> str:
    """Sample a short completion with the chat template, thinking disabled."""
    import torch
    messages = [{"role": "user", "content": user_text}]
    try:
        chat = reader.tok.apply_chat_template(messages, tokenize=False, add_generation_prompt=True,
                                              enable_thinking=False)
    except TypeError:
        chat = reader.tok.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    ids = reader.tok(chat, return_tensors="pt", add_special_tokens=False)
    torch.manual_seed(seed)
    with torch.no_grad():
        out = reader.model.generate(**ids, max_new_tokens=max_new_tokens, do_sample=True,
                                    temperature=temperature, top_p=0.95,
                                    pad_token_id=reader.tok.eos_token_id)
    text = reader.tok.decode(out[0, ids["input_ids"].shape[1]:], skip_special_tokens=True)
    return " ".join(text.strip().split())


def motivation_pool(reader: LogitReader, n_per_label: int, seed: int = 0, temperature: float = 1.0
                    ) -> dict[str, list[str]]:
    pool: dict[str, list[str]] = {}
    for lab in LABELS:
        pool[lab] = [generate_text(reader, MOTIVATION_PROMPT.format(a=LABELS[0], b=LABELS[1], label=lab),
                                   max_new_tokens=40, temperature=temperature, seed=seed * 1000 + i)
                     for i in range(n_per_label)]
    return pool


def build_prompt_motivation(wording: str, states: tuple[int, ...], plus_label: str,
                            motivations: list[str] | None, memory: tuple[int, ...] = ()) -> str:
    """Peers rendered as numbered lines 'i. LABEL: motivation' (or 'i. LABEL')."""
    minus_label = LABELS[1] if plus_label == LABELS[0] else LABELS[0]
    lines = []
    for i, s in enumerate(states):
        lab = plus_label if s == 1 else minus_label
        lines.append(f"{i + 1}. {lab}: {motivations[i]}" if motivations else f"{i + 1}. {lab}")
    peers = "\n" + "\n".join(lines)
    return wording.format(a=LABELS[0], b=LABELS[1], n_peers=len(states), peers=peers,
                          memory=render_memory(memory, plus_label))


def draw_motivations(states: tuple[int, ...], plus_label: str, pool: dict[str, list[str]],
                     rng: np.random.Generator, shuffled: bool) -> list[str]:
    """One motivation per peer, matching its shown label (or a random label
    when ``shuffled``), drawn without replacement within a prompt."""
    minus_label = LABELS[1] if plus_label == LABELS[0] else LABELS[0]
    used: dict[str, set] = {LABELS[0]: set(), LABELS[1]: set()}
    out = []
    for s in states:
        lab = plus_label if s == 1 else minus_label
        if shuffled:
            lab = LABELS[int(rng.integers(2))]
        choices = [i for i in range(len(pool[lab])) if i not in used[lab]] or list(range(len(pool[lab])))
        i = int(rng.choice(choices))
        used[lab].add(i)
        out.append(pool[lab][i])
    return out
